import { test, expect } from '@playwright/test'
test('mobile interface and actions', async ({ page }) => {
  await page.setViewportSize({width:390,height:844})
  await page.goto('/')
  await expect(page.getByText('Hi, Aafreen!')).toBeVisible()
  await expect(page.getByRole('heading', {name:'How can I help you?'})).toBeVisible()
  await expect(page.getByAltText('AI avatar of Aafreen')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button',{name:'Translate'}).click()
  await expect(page.getByRole('textbox')).toHaveValue('Translate this text: ')
  await page.getByRole('textbox').fill('Hello')
  await page.getByRole('button',{name:'Send message'}).click()
  await expect(page.getByText('This is a UI preview. Connect an AI service to get a personalized response.')).toBeVisible()
  await page.getByRole('button',{name:'Clear conversation'}).click()
  await page.getByRole('button',{name:'Audio Chat'}).click()
  await expect(page.getByRole('status')).toContainText('voice service')
})
